/** Whether a method is called with an object or with nothing. */
type MethodArgs = "object" | "none";

type MainMethodTable = Readonly<Record<(typeof METHOD_NAMES)[number], { readonly args: MethodArgs }>>;

export const MAIN_METHOD_TABLE: MainMethodTable = Object.fromEntries(
  METHOD_NAMES.map((name) => [name, { args: NO_ARGUMENT.has(name) ? "none" : "object" }]),
) as MainMethodTable;

export type MainMethod = keyof typeof MAIN_METHOD_TABLE;

export function isMainMethod(name: string): name is MainMethod {
  return Object.hasOwn(MAIN_METHOD_TABLE, name);
}
